package com.weatherwear.assistant.domain

/** Расшифровка кодов погоды WMO, которые отдаёт Open-Meteo. */
object WeatherCodes {

    fun description(code: Int): String = when (code) {
        0 -> "Ясно"
        1 -> "Преимущественно ясно"
        2 -> "Переменная облачность"
        3 -> "Пасмурно"
        45 -> "Туман"
        48 -> "Изморозь"
        51 -> "Слабая морось"
        53 -> "Морось"
        55 -> "Сильная морось"
        56 -> "Ледяная морось"
        57 -> "Сильная ледяная морось"
        61 -> "Небольшой дождь"
        63 -> "Дождь"
        65 -> "Сильный дождь"
        66 -> "Ледяной дождь"
        67 -> "Сильный ледяной дождь"
        71 -> "Небольшой снег"
        73 -> "Снег"
        75 -> "Сильный снег"
        77 -> "Снежные зёрна"
        80 -> "Небольшой ливень"
        81 -> "Ливень"
        82 -> "Сильный ливень"
        85 -> "Снегопад"
        86 -> "Сильный снегопад"
        95 -> "Гроза"
        96 -> "Гроза с градом"
        99 -> "Сильная гроза с градом"
        else -> "Погода без особенностей"
    }

    fun emoji(code: Int, isDay: Boolean = true): String = when (code) {
        0 -> if (isDay) "☀️" else "🌙"
        1 -> if (isDay) "🌤️" else "🌙"
        2 -> "⛅"
        3 -> "☁️"
        45, 48 -> "🌫️"
        51, 53, 55, 56, 57 -> "🌦️"
        61, 63, 65, 66, 67, 80, 81, 82 -> "🌧️"
        71, 73, 75, 77, 85, 86 -> "🌨️"
        95, 96, 99 -> "⛈️"
        else -> "🌡️"
    }

    fun isSnow(code: Int): Boolean = code in intArrayOf(71, 73, 75, 77, 85, 86)

    fun isRain(code: Int): Boolean =
        code in intArrayOf(51, 53, 55, 56, 57, 61, 63, 65, 66, 67, 80, 81, 82, 95, 96, 99)

    fun isThunder(code: Int): Boolean = code in intArrayOf(95, 96, 99)

    fun isFog(code: Int): Boolean = code == 45 || code == 48

    /** Ледяной дождь и изморозь — главные кандидаты на гололёд. */
    fun isFreezingPrecipitation(code: Int): Boolean = code in intArrayOf(48, 56, 57, 66, 67)
}
